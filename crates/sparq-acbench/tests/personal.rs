/// Determinism invariant: same seed → byte-identical N-Quads.
///
/// Exercises the core benchmark credibility guarantee (§2.1 design record):
/// identical `GenParams` produces byte-identical output on every run.
#[test]
fn generate_u1_determinism() {
    use sparq_acbench::{personal, GenParams};
    let params = GenParams::smoke();
    let ds1 = personal::generate(&params);
    let ds2 = personal::generate(&params);
    assert_eq!(
        ds1.data_nquads, ds2.data_nquads,
        "U1 generator must be deterministic: same seed → same N-Quads"
    );
    assert_eq!(
        ds1.expected_decisions.len(),
        ds2.expected_decisions.len(),
        "U1 generator must be deterministic: same seed → same number of expected decisions"
    );
}

/// Oracle fail-closed: every WAC expected decision in the corpus must match the
/// by-construction oracle result.
///
/// This is the central oracle soundness check: the `expected_decisions` field
/// is generated by the same oracle, so this test is effectively a round-trip
/// check. A mismatch would indicate a bug in the decision generation loop.
#[test]
fn generate_u1_oracle_fail_closed() {
    use sparq_acbench::{oracle_wac, personal, GenParams};
    let params = GenParams::smoke();
    let ds = personal::generate(&params);
    // Every expected decision in the WAC lane must match the oracle.
    for ed in ds
        .expected_decisions
        .iter()
        .filter(|e| e.model == sparq_acbench::AcModel::Wac)
    {
        let oracle_result = oracle_wac(&ed.request, &ds.intents);
        assert_eq!(
            oracle_result, ed.decision,
            "U1 WAC oracle mismatch for request {:?}",
            ed.request
        );
    }
}

/// Owner-always-allowed invariant: the pod owner must be granted Allow on every
/// resource under WAC (the canonical owner-centric Solid pod shape).
#[test]
fn owner_always_allowed_wac() {
    use sparq_acbench::{personal, AcModel, AccessMode, Decision, GenParams, Request};
    let params = GenParams::smoke();
    let ds = personal::generate(&params);

    // Extract owner URI from the first WAC expected decision.
    // The owner is the agent that has Allow on ALL resources.
    let owner_ed = ds
        .expected_decisions
        .iter()
        .find(|e| e.model == AcModel::Wac && e.decision == Decision::Allow)
        .expect("U1 must produce at least one Allow decision");
    let owner_uri = &owner_ed.request.agent;

    // Collect all unique resource URIs from the intent table.
    let resource_uris: Vec<String> = ds
        .intents
        .iter()
        .map(|r| r.resource_uri.clone())
        .collect::<std::collections::HashSet<_>>()
        .into_iter()
        .collect();

    for resource_uri in &resource_uris {
        let req = Request {
            agent: owner_uri.clone(),
            client: None,
            resource: resource_uri.clone(),
            mode: AccessMode::read_only(),
        };
        // Owner must be allowed for every resource that the owner owns
        // (pod root subtree intent covers all resources in the pod).
        let decision = sparq_acbench::oracle_wac(&req, &ds.intents);
        // The owner subtree grant covers any URI starting with the pod root.
        // Resources in the pod start with the pod base URI, so all should be Allow.
        assert_eq!(
            decision,
            Decision::Allow,
            "Owner must have WAC Allow on resource {resource_uri}"
        );
    }
}

/// Unknown-agent-deny: an agent not listed in any policy must be Denied on
/// non-public resources (fail-closed default).
#[test]
fn unknown_agent_denied_on_private_resources() {
    use sparq_acbench::{personal, AcModel, AccessMode, Decision, GenParams, Request};
    let params = GenParams::smoke();
    let ds = personal::generate(&params);

    let unknown = "https://pod.example/unknown/profile/card#me";
    // Find at least one expected Deny for the unknown agent in the WAC lane.
    let deny_count = ds
        .expected_decisions
        .iter()
        .filter(|e| {
            e.model == AcModel::Wac && e.request.agent == unknown && e.decision == Decision::Deny
        })
        .count();

    assert!(
        deny_count > 0,
        "U1 must produce at least one WAC Deny for the unknown agent (fail-closed)"
    );

    // Verify each Deny round-trips through the oracle.
    for ed in ds
        .expected_decisions
        .iter()
        .filter(|e| e.model == AcModel::Wac && e.request.agent == unknown)
    {
        let oracle = sparq_acbench::oracle_wac(&ed.request, &ds.intents);
        assert_eq!(
            oracle, ed.decision,
            "Oracle mismatch for unknown agent request"
        );
    }

    // Also verify: an explicit request for an unlisted resource URI returns Deny.
    let unlisted_req = Request {
        agent: unknown.to_string(),
        client: None,
        resource: "https://pod.example/user42/nonexistent/resource999".to_string(),
        mode: AccessMode::read_only(),
    };
    let decision = sparq_acbench::oracle_wac(&unlisted_req, &ds.intents);
    assert_eq!(
        decision,
        Decision::Deny,
        "Fail-closed: unlisted resource must return Deny"
    );
}

