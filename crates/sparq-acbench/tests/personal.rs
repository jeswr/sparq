/// Expressibility matrix: ClientRestricted audience must be Approximation in WAC
/// and Native in ACP and ODRL (design record §2.2 documented asymmetry).
#[test]
fn expressibility_matrix_client_restricted() {
    use sparq_acbench::{
        personal, AcModel, AccessMode, Audience, Condition, Effect, Expressibility, GenParams,
        IntentRow, Scope,
    };
    // Build a minimal ClientRestricted intent row to probe the expressibility matrix.
    let row = IntentRow {
        audience: Audience::ClientRestricted {
            agent: "https://agent.example/a#me".to_string(),
            client: "https://app.example/myapp".to_string(),
        },
        scope: Scope::Resource,
        mode: AccessMode::read_only(),
        condition: Condition::None,
        effect: Effect::Allow,
        resource_uri: "https://pod.example/res1".to_string(),
    };

    let wac_expr = personal::wac_expressibility(&row);
    let acp_expr = personal::acp_expressibility(&row, &[]);
    let odrl_expr = personal::odrl_expressibility(&row);

    assert_eq!(
        wac_expr,
        Expressibility::Approximation,
        "WAC ClientRestricted must be Approximation (acl:origin approximates acp:client)"
    );
    assert_eq!(
        acp_expr,
        Expressibility::Native,
        "ACP ClientRestricted must be Native (acp:client)"
    );
    assert_eq!(
        odrl_expr,
        Expressibility::Native,
        "ODRL ClientRestricted must be Native"
    );

    // Unused import guard: reference GenParams and AcModel to avoid dead_code warnings.
    let _ = (AcModel::Wac, GenParams::smoke());
}

/// Expressibility matrix: Group audience must be Native in WAC, Expansion in ACP
/// (per-member expansion), Native in ODRL (odrl:PartyCollection).
#[test]
fn expressibility_matrix_group() {
    use sparq_acbench::{
        personal, AcModel, AccessMode, Audience, Condition, Effect, Expressibility, GenParams,
        IntentRow, Scope,
    };
    let row = IntentRow {
        audience: Audience::Group("https://pod.example/groups/friends/".to_string()),
        scope: Scope::Resource,
        mode: AccessMode::read_only(),
        condition: Condition::None,
        effect: Effect::Allow,
        resource_uri: "https://pod.example/res2".to_string(),
    };

    let wac_expr = personal::wac_expressibility(&row);
    let acp_expr_resolved = personal::acp_expressibility(
        &row,
        &[
            "https://agent.example/a1#me".to_string(),
            "https://agent.example/a2#me".to_string(),
        ],
    );
    let odrl_expr = personal::odrl_expressibility(&row);

    assert_eq!(
        wac_expr,
        Expressibility::Native,
        "WAC Group must be Native (acl:agentGroup)"
    );
    // ACP expands group to per-member matchers: Expansion(2) for 2 members.
    assert_eq!(
        acp_expr_resolved,
        Expressibility::Expansion(2),
        "ACP Group with 2 members must be Expansion(2)"
    );
    assert_eq!(
        odrl_expr,
        Expressibility::Native,
        "ODRL Group must be Native (odrl:PartyCollection)"
    );

    let _ = (AcModel::Wac, GenParams::smoke());
}

