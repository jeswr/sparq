    Object.keys(byGroup).sort().forEach(function (g) {
      if (GROUP_ORDER.indexOf(g) === -1) groups.push({ group: g, rows: sortRows(byGroup[g]) });
    });
    return { commit: latest.commit, date: latest.date, groups: groups };
