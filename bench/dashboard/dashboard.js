  // ---- metric-label registry (sq-ocuf) -------------------------------------

  // metric-labels.json is { labels: { "<stem>": {label,suite,...} }, ... }; boot() fetches it into
  // window.METRIC_LABELS. Accessor tolerates the full file object, a bare {stem:rec} map, OR total
  // absence (-> {} -> heuristic fallback), so the dashboard never hard-depends on it.
  function labelMap() {
    var m = (typeof window !== 'undefined' && window.METRIC_LABELS) ||
            (typeof global !== 'undefined' && global.METRIC_LABELS) || {};
    return (m && m.labels) ? m.labels : m;
  }

  // Stems in the map are name-minus-`_us` (e.g. `watdiv_S1_count`); byte/second metrics are
  // keyed by their exact name. Look up by stem first, then by the raw name.
  function lookup(name) {
    var map = labelMap();
    return map[name.replace(/_us$/, '')] || map[name] || null;
  }

  // Readable label for a metric (falls back to humanize() when unlabelled).
  function labelFor(name) {
    var rec = lookup(name);
    return rec && rec.label ? rec.label : humanize(name);
  }

  // [OPUS-4.8] Unit-LESS readable label — same as labelFor() but with any trailing ` (<unit>)`
  // stripped. Used where the unit is shown in a SEPARATE cell/column (the featured table's metric
  // cell, sq-xvow; the scaling card title, sq-viby) so the unit isn't printed twice. The label map
  // labels (sq-ocuf) don't carry a trailing unit, so this only bites the humanize() fallback (which
  // appends `(µs)`/`(s)` for UNLABELLED metrics like Deep Taxonomy). We strip ONLY a trailing
  // parenthesised token, leaving mid-label parentheses (e.g. "LUBM (reasoning)") untouched.
  function labelForBare(name) {
    return labelFor(name).replace(/\s*\([^()]*\)\s*$/, '').trim();
  }

  // A rich tooltip/title for a metric: the raw stem first (transparency), then dataset + query.
  function titleFor(name) {
    var rec = lookup(name);
    var parts = [name];
    if (rec) {
      if (rec.dataset) parts.push('dataset: ' + rec.dataset);
      if (rec.query) parts.push('query: ' + rec.query);
    }
    return parts.join('\n');
  }

  // [OPUS-4.8] sq-19z8: per-metric SEMANTIC badges derived from the label record (sq-ocuf already
  // emits `regime` for LUBM — extensional vs entailed OWL-RL closure — and `mode` for the result
  // shape — count/materialize/json/…). These two fields previously surfaced ONLY in the title-attr
  // tooltip; this returns small badge descriptors so the renderer can show them as muted pills next
  // to the metric label, making the reasoning delta + serialization mode visible at a glance.
  //
  // Returns an ordered array of { kind, text, title } (empty when the metric has neither field, e.g.
  // a load/store/dict metric, so most rows stay badge-free). `kind` is a CSS-class suffix:
  //   - regime -> 'badge-entailed' (LUBM reasoning, OWL-RL closure) or 'badge-extensional' (asserted
  //     triples only, no entailment). The entailed/extensional split is the reasoning delta.
  //   - mode   -> 'badge-mode' (count / materialize / json / closure / validate / …), the result
  //     serialization/consumption mode the latency was measured under.
  // Pure + node-testable. We DO NOT invent badges for unlabelled metrics (lookup() returns null ->
  // []), so the structural-fallback path never sprouts a misleading pill.
  function semanticBadges(name) {
    var rec = lookup(name);
    if (!rec) return [];
    var out = [];
    if (rec.regime) {
      var entailed = rec.regime === 'entailed';
      out.push({
        kind: entailed ? 'badge-entailed' : 'badge-extensional',
        text: rec.regime,
        title: entailed
          ? 'entailed — measured over the OWL-RL closure (materialised entailments), so this is the reasoning-on path'
          : 'extensional — measured over the asserted triples only (no entailment / closure)'
      });
    }
    if (rec.mode) {
      out.push({
        kind: 'badge-mode',
        text: rec.mode,
        title: 'result mode: ' + rec.mode +
          ' — the serialization/consumption mode this latency was measured under'
      });
    }
    return out;
  }

  // The suite a metric belongs to (drives table sections + chart groups). Falls back to the old
  // structural classifier so an unlabelled metric is grouped, never orphaned.
  function suiteFor(name) {
    var rec = lookup(name);
    return rec && rec.suite ? rec.suite : classify(name).group;
  }

  // ---- pure helpers (node-testable) ----------------------------------------

  // STRUCTURAL FALLBACK classifier — used only when a metric is missing from metric-labels.json
  // (the label map is the source of truth otherwise). Query/operator latencies:
  // qNN_<query>_<mode>_us and op_<query>_<mode>_us.
  function classify(name) {
    var m = name.match(/^(q\d+|op)_(.+)_(count|materialize|json)_us$/);
    if (m) {
      var fam = m[1] === 'op' ? 'operator' : 'query';
      var query = m[2].replace(/_/g, ' ');
      return { group: fam[0].toUpperCase() + fam.slice(1) + ' latency',
               label: query + ' · ' + m[3] };
    }
    if (/^(store_|dict_)/.test(name) || /_bytes$/.test(name) ||
        name === 'parse_ns_per_byte' || name === 'wasm_bundle_bytes') {
      return { group: 'Memory / Size', label: humanize(name) };
    }
    if (name === 'load_s' || name === 'rdfs_infer_s') {
      return { group: 'Pipeline', label: humanize(name) };
    }
    return { group: 'Other', label: humanize(name) };
  }

  function humanize(name) {
    return name
      .replace(/_us$/, ' (µs)')
      .replace(/_s$/, ' (s)')
      .replace(/_/g, ' ')
      .replace(/\bns per byte\b/, 'ns/byte')
      .trim();
  }

  // Best (minimum, since smaller-is-better) value for a metric over ALL commits in the series.
  function bestOf(entries, name) {
    var best = Infinity;
    for (var i = 0; i < entries.length; i++) {
      var benches = entries[i].benches;
      for (var j = 0; j < benches.length; j++) {
        if (benches[j].name === name && benches[j].value < best) best = benches[j].value;
      }
    }
    return best === Infinity ? null : best;
  }

  // Δ-vs-best descriptor: best (latest is the all-time min) or +x.x% worse.
  function deltaVsBest(latestValue, best) {
    if (best == null || best === 0) {
      return { kind: latestValue === best ? 'best' : 'na', pct: 0 };
    }
    if (latestValue <= best) return { kind: 'best', pct: 0 };
    var pct = (latestValue - best) / best * 100;
    return { kind: 'worse', pct: pct };
  }

  function fmtNum(v) {
    if (v == null) return '—';
    if (v === 0) return '0';
    var abs = Math.abs(v);
    if (abs >= 1000) return v.toLocaleString('en-US', { maximumFractionDigits: 0 });
    if (abs >= 1) return (Math.round(v * 100) / 100).toLocaleString('en-US');
    return (Math.round(v * 10000) / 10000).toString();
  }

  // Build the ordered list of summary rows grouped by SUITE. Stable suite order: pipeline/memory
  // first, then the engine micro-suites, then the well-known suites (the featured-suites section
